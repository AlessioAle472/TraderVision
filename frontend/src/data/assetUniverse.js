/**
 * Fast synchronous search helper on client with 0ms response time
 */
export const searchClientAssets = (query) => {
  if (!query || typeof query !== 'string') return [];
  const cleanQ = query.trim().toLowerCase();
  if (cleanQ.length === 0) return [];

  const exactMatches = [];
  const startsWithMatches = [];
  const otherMatches = [];

  for (const asset of ASSET_UNIVERSE) {
    const t = asset.ticker.toLowerCase();
    const n = asset.name.toLowerCase();
    const y = (asset.yahooTicker || '').toLowerCase();
    const kw = asset.keywords || [];

    if (t === cleanQ || y === cleanQ) {
      exactMatches.push(asset);
    } else if (t.startsWith(cleanQ)) {
      startsWithMatches.push(asset);
    } else if (
      t.includes(cleanQ) ||
      n.includes(cleanQ) ||
      y.includes(cleanQ) ||
      kw.some(k => k.toLowerCase().includes(cleanQ))
    ) {
      otherMatches.push(asset);
    }
  }

  return [...exactMatches, ...startsWithMatches, ...otherMatches].slice(0, 10);
};

export default ASSET_UNIVERSE;
